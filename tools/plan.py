"""RulerCraft plan tool: check the plan files, render STATUS.md and ROADMAP-PROGRESS.md, suggest the next task.

  python3 tools/plan.py check    # exit 1 on an invalid plan or stale generated files
  python3 tools/plan.py render   # rewrite the generated files
  python3 tools/plan.py next     # ready, unclaimed features first
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STATUSES = {"planned": 0.0, "specced": 0.15, "in-progress": 0.3, "implemented": 0.75, "verified": 0.9, "done": 1.0}
DONEISH = {"implemented", "verified", "done"}
CHECKS = {"math", "known-design", "reference", "wrong-value", "fuzz"}
FIELDS = ["id", "milestone", "title", "spec", "status", "depends_on", "owner", "pr", "verified_by", "left"]


def load(root=ROOT):
    roadmap = json.loads((root / "plan/roadmap.json").read_text())
    features = [json.loads(p.read_text()) for p in sorted((root / "plan/features").glob("*.json"))]
    return roadmap, features


def validate(roadmap, features, root=ROOT):
    errors = []
    milestones = {m["id"] for m in roadmap["milestones"]}
    ids = [f.get("id") for f in features]
    if len(set(ids)) != len(ids):
        errors.append("duplicate feature id")
    known = set(ids)
    for f in features:
        fid = f.get("id", "<missing id>")
        missing = [k for k in FIELDS if k not in f]
        if missing:
            errors.append(f"{fid}: missing fields {missing}")
            continue
        if not (root / f"plan/features/{fid}.json").exists():
            errors.append(f"{fid}: file name must match id")
        if f["milestone"] not in milestones:
            errors.append(f"{fid}: unknown milestone {f['milestone']}")
        if f["status"] not in STATUSES:
            errors.append(f"{fid}: unknown status {f['status']}")
        for d in f["depends_on"]:
            if d not in known:
                errors.append(f"{fid}: unknown dependency {d}")
        if f["spec"] and not (root / f"docs/specs/{f['spec']}.md").exists():
            errors.append(f"{fid}: missing spec docs/specs/{f['spec']}.md")
        if not set(f["verified_by"]) <= CHECKS:
            errors.append(f"{fid}: verified_by must be from {sorted(CHECKS)}")
        if f["status"] in {"verified", "done"} and not {"math", "wrong-value"} <= set(f["verified_by"]):
            errors.append(f"{fid}: verified needs at least math and wrong-value checks")
        if f["status"] == "in-progress" and not f["owner"]:
            errors.append(f"{fid}: in-progress needs an owner")
    seen, stack = set(), set()
    by_id = {f["id"]: f for f in features if "id" in f}

    def visit(i):
        if i in stack:
            errors.append(f"dependency cycle through {i}")
            return
        if i in seen or i not in by_id:
            return
        stack.add(i)
        for d in by_id[i]["depends_on"]:
            visit(d)
        stack.discard(i)
        seen.add(i)

    for i in by_id:
        visit(i)
    return errors


def progress(roadmap, features):
    rows, total = [], 0.0
    weights = sum(m["weight"] for m in roadmap["milestones"])
    for m in roadmap["milestones"]:
        mine = [f for f in features if f["milestone"] == m["id"]]
        pct = sum(STATUSES[f["status"]] for f in mine) / len(mine) if mine else 0.0
        total += pct * m["weight"] / weights
        rows.append((m, mine, pct))
    return rows, total


def bar(p):
    n = round(p * 10)
    return "`" + "█" * n + "░" * (10 - n) + "`"


def render_progress(roadmap, features):
    rows, total = progress(roadmap, features)
    out = ["# Roadmap progress", "", "Generated by `python3 tools/plan.py render` from `plan/`; do not hand-edit.", "",
           "Feature credit: " + ", ".join(f"{k} {v:g}" for k, v in STATUSES.items()) +
           ". A milestone is finished by its exit condition, not by this number.", "",
           f"**Overall: {round(total * 100)}%**", "", "| Milestone | Progress | % | Weight | Exit condition |", "| --- | --- | ---: | ---: | --- |"]
    for m, _, p in rows:
        out.append(f"| {m['id']} {m['title']} | {bar(p)} | {round(p * 100)}% | {m['weight']} | {m['exit']} |")
    for m, mine, p in rows:
        out += ["", f"## {m['id']}: {m['title']} ({round(p * 100)}%)", "", "| Feature | Status | Verified by | Owner / PR | Left |", "| --- | --- | --- | --- | --- |"]
        for f in mine:
            who = " ".join(x for x in [f["owner"] or "", f["pr"] or ""] if x) or "unclaimed"
            out.append(f"| `{f['id']}` {f['title']} | {f['status']} | {', '.join(f['verified_by']) or '-'} | {who} | {f['left']} |")
    return "\n".join(out) + "\n"


def ready(features):
    by_id = {f["id"]: f for f in features}
    return [f for f in features if f["status"] in {"planned", "specced"} and not f["owner"]
            and all(by_id[d]["status"] in DONEISH for d in f["depends_on"])]


def render_status(roadmap, features):
    rows, total = progress(roadmap, features)
    counts = {s: sum(1 for f in features if f["status"] == s) for s in STATUSES}
    active = [f for f in features if f["status"] == "in-progress"]
    out = ["# Status", "", "Generated by `python3 tools/plan.py render`; do not hand-edit. Narrative and open threads: HANDOFF.md.", "",
           f"Overall roadmap progress: **{round(total * 100)}%** (details in ROADMAP-PROGRESS.md).", "",
           "| Status | Features |", "| --- | ---: |"] + [f"| {s} | {n} |" for s, n in counts.items()]
    out += ["", "## In progress", ""] + ([f"- `{f['id']}` ({f['owner']}{', ' + f['pr'] if f['pr'] else ''}): {f['left']}" for f in active] or ["- none"])
    out += ["", "## Ready to claim", ""] + ([f"- `{f['id']}` ({f['milestone']}): {f['title']}" for f in ready(features)] or ["- none"])
    return "\n".join(out) + "\n"


def outputs(root=ROOT):
    roadmap, features = load(root)
    return {root / "STATUS.md": render_status(roadmap, features), root / "ROADMAP-PROGRESS.md": render_progress(roadmap, features)}


def main(argv):
    cmd = argv[1] if len(argv) > 1 else "check"
    roadmap, features = load()
    errors = validate(roadmap, features)
    if errors:
        print("\n".join(errors))
        return 1
    if cmd == "render":
        for path, text in outputs().items():
            path.write_text(text)
        print("wrote STATUS.md and ROADMAP-PROGRESS.md")
    elif cmd == "check":
        stale = [p.name for p, t in outputs().items() if not p.exists() or p.read_text() != t]
        print(f"plan ok: {len(features)} features, {len(roadmap['milestones'])} milestones")
        if stale:
            # Parallel merges leave these stale all the time; that is not an error. Whoever merges
            # runs `tools/plan.py render`. `--strict` turns this into a failure when wanted.
            print("note: generated files out of date, run `python3 tools/plan.py render`: " + ", ".join(stale))
            if "--strict" in sys.argv:
                return 1
    elif cmd == "next":
        r = ready(features)
        print("Ready and unclaimed:" if r else "Nothing ready and unclaimed.")
        for f in r:
            print(f"  {f['id']:20} {f['milestone']}  {f['title']}")
        claimed = [f for f in features if f["status"] == "in-progress"]
        if claimed:
            print("In progress:")
            for f in claimed:
                print(f"  {f['id']:20} {f['owner']} {f['pr'] or ''}")
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
